/** Escape a label for a quoted Graphviz string, keeping "\n" as line breaks. */
function esc(text) {
  return String(text)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
}

/** One node with the style of its colour kind. */
function node(id, label, kind = "code") {
  const style = KINDS[kind];
  const attributes = [
    `label="${esc(label)}"`,
    `fillcolor="${style.fill}"`,
    `color="${style.border}"`,
    `fontcolor="#1B1B1B"`,
    `shape=${style.shape || "box"}`,
    style.shape === "cylinder" ? `style="filled"` : `style="rounded,filled"`,
  ];
  return `  ${id} [${attributes.join(", ")}];`;
}

/**
 * One edge; a red one marks the rejected / error branch. `toCluster` draws the
 * arrow to the border of a cluster instead of to a single node.
 */
function edge(from, to, label = "", red = false, toCluster = false) {
  const attributes = [`color="${red ? "#C0392B" : "#666666"}"`];
  if (label) attributes.push(`label="${esc(label)}"`);
  if (red) attributes.push(`fontcolor="#C0392B"`);
  if (toCluster) attributes.push(`lhead=cluster_${to}`);
  return `  ${from} -> ${toCluster ? `cluster_${to}` : to} [${attributes.join(", ")}];`;
}

/**
 * A cluster holding the legend: one small box per colour the diagram uses.
 *
 * @param {string} prefix unique node id prefix (one per diagram)
 * @param {string[]} used kinds to show, in legend order
 */
function legend(prefix, used) {
  const nodes = used.map((kind) => {
    const style = KINDS[kind];
    return `    ${prefix}_${kind} [label="${esc(style.legend)}", fillcolor="${style.fill}", color="${style.border}", fontcolor="#1B1B1B", shape=${style.shape || "box"}, style="${style.shape === "cylinder" ? "filled" : "rounded,filled"}", fontsize=9];`;
  });
  const same = `    { rank=same; ${used.map((kind) => `${prefix}_${kind}`).join("; ")}; }`;
  return [
    "  subgraph cluster_legend {",
    '    label="图例";',
    '    fontsize=11;',
    '    style="rounded,dashed";',
    '    color="#999999";',
    "    node [fontname=\"" + FONT + "\", margin=\"0.10,0.05\"];",
    ...nodes,
    same,
    "  }",
  ].join("\n");
}

/** Wrap a body plus its legend into one complete digraph source. */
function digraph(name, body, used, rankdir = "LR") {
  const gid = name.replace(/[^A-Za-z0-9_]/g, "_"); // "data-build" is not a valid id
  return [
    `// ${name}.dot - generated by documentation/diagrams/build.mjs.`,
    `// Edit the script, then run: npm run docs:diagrams`,
    `digraph ${gid} {`,
    `  graph [rankdir=${rankdir}, compound=true, fontname="${FONT}", fontsize=12,`,
    '         bgcolor="white", pad="0.25", nodesep="0.35", ranksep="0.55"];',
    `  node [fontname="${FONT}", fontsize=11, margin="0.16,0.09"];`,
    `  edge [fontname="${FONT}", fontsize=10, arrowsize=0.7];`,
    body.trimEnd(),
    legend("legend", used),
    "}",
    "",
  ].join("\n");
}

